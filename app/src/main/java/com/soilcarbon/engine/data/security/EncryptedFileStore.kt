package com.soilcarbon.engine.data.security

import com.soilcarbon.engine.core.Dispatchers
import com.soilcarbon.engine.domain.model.ProvenanceHasher
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.security.MessageDigest
import javax.crypto.Cipher
import javax.crypto.CipherInputStream
import javax.crypto.CipherOutputStream
import javax.crypto.spec.GCMParameterSpec

data class SecureFile(
    val relativePath: String,
    val sha256: String,
    val sizeBytes: Long
)

/**
 * AES-256-GCM envelope for every captured image and exported bundle. Format:
 *
 *   "SCF1" | iv_len(1) | iv | ciphertext | tag
 *
 * The per-file random IV is generated by the Keystore-backed cipher. Plaintext never touches
 * external storage; decrypted temporary copies live in the app cache and are deleted by the
 * caller. The SHA-256 is computed over plaintext so it matches the provenance record.
 */
class EncryptedFileStore(
    private val rootDir: File,
    private val secretStore: KeystoreSecretStore
) {
    private val random = java.security.SecureRandom()

    init {
        if (!rootDir.exists()) rootDir.mkdirs()
    }

    suspend fun importFile(source: File, relativePath: String): SecureFile = withContext(Dispatchers.io) {
        require(source.exists()) { "Source file does not exist: ${source.name}" }
        val target = File(rootDir, relativePath).apply { parentFile?.mkdirs() }
        val digest = MessageDigest.getInstance("SHA-256")
        val iv = ByteArray(12).also(random::nextBytes)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, fileKey(), GCMParameterSpec(128, iv))

        var total = 0L
        FileInputStream(source).use { input ->
            FileOutputStream(target).use { output ->
                output.write(MAGIC)
                output.write(iv.size)
                output.write(iv)
                CipherOutputStream(output, cipher).use { encrypted ->
                    val buffer = ByteArray(64 * 1024)
                    while (true) {
                        val read = input.read(buffer)
                        if (read <= 0) break
                        digest.update(buffer, 0, read)
                        encrypted.write(buffer, 0, read)
                        total += read
                    }
                }
            }
        }
        SecureFile(relativePath, ProvenanceHasher.sha256Hex(digest.digest()), total)
    }

    suspend fun writeBytes(relativePath: String, bytes: ByteArray): SecureFile =
        withContext(Dispatchers.io) {
            val target = File(rootDir, relativePath).apply { parentFile?.mkdirs() }
            val digest = MessageDigest.getInstance("SHA-256").digest(bytes)
            val iv = ByteArray(12).also(random::nextBytes)
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, fileKey(), GCMParameterSpec(128, iv))
            FileOutputStream(target).use { output ->
                output.write(MAGIC)
                output.write(iv.size)
                output.write(iv)
                CipherOutputStream(output, cipher).use { it.write(bytes) }
            }
            SecureFile(relativePath, ProvenanceHasher.sha256Hex(digest), bytes.size.toLong())
        }

    /** Decrypts to a temporary cache file. Callers must delete the returned file afterwards. */
    suspend fun decryptToTemp(relativePath: String, cacheDir: File): File = withContext(Dispatchers.io) {
        val source = File(rootDir, relativePath)
        require(source.exists()) { "Encrypted asset missing: $relativePath" }
        val temp = File.createTempFile("soilcarbon_", ".tmp", cacheDir)
        FileInputStream(source).use { input ->
            val magic = ByteArray(MAGIC.size)
            require(input.read(magic) == MAGIC.size && magic.contentEquals(MAGIC)) {
                "Not a SoilCarbon encrypted file"
            }
            val ivSize = input.read()
            require(ivSize in 12..16) { "Invalid IV length" }
            val iv = ByteArray(ivSize).also { require(input.read(it) == it.size) }
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, fileKey(), GCMParameterSpec(128, iv))
            CipherInputStream(input, cipher).use { decrypted ->
                FileOutputStream(temp).use { output -> decrypted.copyTo(output, 64 * 1024) }
            }
        }
        temp
    }

    fun exists(relativePath: String): Boolean = File(rootDir, relativePath).exists()

    fun delete(relativePath: String): Boolean = File(rootDir, relativePath).delete()

    fun absolutePath(relativePath: String): File = File(rootDir, relativePath)

    private fun fileKey(): java.security.Key {
        // Dedicated file key: distinct alias from the database wrapping key so rotation can be
        // performed independently.
        val keyStore = java.security.KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (keyStore.getEntry(FILE_ALIAS, null) as? java.security.KeyStore.SecretKeyEntry)
            ?.let { return it.secretKey }
        val generator = javax.crypto.KeyGenerator.getInstance(
            android.security.keystore.KeyProperties.KEY_ALGORITHM_AES,
            "AndroidKeyStore"
        )
        val spec = android.security.keystore.KeyGenParameterSpec.Builder(
            FILE_ALIAS,
            android.security.keystore.KeyProperties.PURPOSE_ENCRYPT or
                android.security.keystore.KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(android.security.keystore.KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(android.security.keystore.KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .build()
        generator.init(spec)
        return generator.generateKey()
    }

    private companion object {
        val MAGIC = byteArrayOf('S'.code.toByte(), 'C'.code.toByte(), 'F'.code.toByte(), '1'.code.toByte())
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val FILE_ALIAS = "soilcarbon_file_key_v1"
    }
}
